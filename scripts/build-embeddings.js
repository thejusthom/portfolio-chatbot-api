// scripts/build-embeddings.js — RAG ingestion pipeline
//
// Reads knowledge/*.md, splits each file into chunks (one per "## " section),
// embeds every chunk with Gemini, and writes the vectors to data/embeddings.js.
//
// Run whenever the knowledge base changes:  npm run embed
// Commit the regenerated data/embeddings.js so Vercel bundles it.

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import dotenv from 'dotenv';

dotenv.config();

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const KNOWLEDGE_DIR = path.join(__dirname, '..', 'knowledge');
const OUTPUT_FILE = path.join(__dirname, '..', 'data', 'embeddings.js');

const EMBEDDING_MODEL = 'gemini-embedding-001';
const EMBEDDING_DIM = 768;

// ---------- Chunking ----------
// Strategy: each "## " section of a markdown file becomes one chunk.
// Sections here are small (< ~300 words), so no further splitting is needed.
// The heading is kept inside the chunk text — it carries useful semantics
// (dates, role names) that improve embedding quality.
function chunkFile(filename, content) {
  const sections = content.split(/^## /m).slice(1); // drop the "# Title" preamble
  return sections.map((section, i) => {
    const [headingLine, ...bodyLines] = section.split('\n');
    const heading = headingLine.trim();
    return {
      id: `${path.basename(filename, '.md')}-${i}`,
      source: path.basename(filename),
      heading,
      text: `${heading}\n${bodyLines.join('\n').trim()}`,
    };
  });
}

// ---------- Embedding ----------
async function embedText(text, taskType) {
  const url = `https://generativelanguage.googleapis.com/v1beta/models/${EMBEDDING_MODEL}:embedContent?key=${process.env.GEMINI_API_KEY}`;
  const response = await fetch(url, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      model: `models/${EMBEDDING_MODEL}`,
      content: { parts: [{ text }] },
      taskType,
      outputDimensionality: EMBEDDING_DIM,
    }),
  });

  if (!response.ok) {
    const body = await response.text();
    throw new Error(`Embedding API ${response.status}: ${body}`);
  }

  const data = await response.json();
  return normalize(data.embedding.values);
}

// gemini-embedding-001 vectors are only pre-normalized at 3072 dims;
// truncated ones (768) must be re-normalized so dot product == cosine similarity.
function normalize(vector) {
  const norm = Math.sqrt(vector.reduce((sum, v) => sum + v * v, 0));
  return vector.map(v => v / norm);
}

// ---------- Main ----------
async function main() {
  if (!process.env.GEMINI_API_KEY) {
    console.error('❌ GEMINI_API_KEY not set — create a .env file first.');
    process.exit(1);
  }

  const files = fs.readdirSync(KNOWLEDGE_DIR).filter(f => f.endsWith('.md')).sort();
  const chunks = files.flatMap(f =>
    chunkFile(f, fs.readFileSync(path.join(KNOWLEDGE_DIR, f), 'utf8'))
  );

  console.log(`📚 ${files.length} knowledge files → ${chunks.length} chunks\n`);

  for (const chunk of chunks) {
    process.stdout.write(`   embedding ${chunk.id} ... `);
    chunk.embedding = (await embedText(chunk.text, 'RETRIEVAL_DOCUMENT'))
      .map(v => +v.toFixed(6)); // trim precision to keep the output file small
    console.log('ok');
  }

  const output = `// AUTO-GENERATED by scripts/build-embeddings.js — do not edit by hand.
// Regenerate with: npm run embed
export const EMBEDDING_MODEL = '${EMBEDDING_MODEL}';
export const EMBEDDING_DIM = ${EMBEDDING_DIM};
export const CHUNKS = ${JSON.stringify(chunks)};
`;

  fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true });
  fs.writeFileSync(OUTPUT_FILE, output);

  const sizeKb = (fs.statSync(OUTPUT_FILE).size / 1024).toFixed(0);
  console.log(`\n✅ Wrote ${chunks.length} chunks (${EMBEDDING_DIM} dims each) → data/embeddings.js (${sizeKb} KB)`);
}

main();
